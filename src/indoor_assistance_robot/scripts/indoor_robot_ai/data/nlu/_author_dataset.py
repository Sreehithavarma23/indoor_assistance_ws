def main() -> None:
    from collections import Counter

    from src.nlu.normalization import normalize_text

    train_norm = [normalize_text(row["text"]) for row in TRAIN]
    test_norm = [normalize_text(row["text"]) for row in TEST]
    if len(train_norm) != len(set(train_norm)):
        raise SystemExit("Duplicate train sentences.")
    if len(test_norm) != len(set(test_norm)):
        raise SystemExit("Duplicate test sentences.")
    overlap = set(train_norm) & set(test_norm)
    if overlap:
        raise SystemExit(f"Train/test overlap: {overlap}")
    dump("train", TRAIN)
    dump("test", TEST)
    print("train intents", dict(Counter(row["intent"] for row in TRAIN)))
    print("test intents", dict(Counter(row["intent"] for row in TEST)))


if __name__ == "__main__":
    main()
